import { chromium } from "playwright-core";
import { execSync } from "child_process";
const EXE = execSync("ls -d /opt/pw-browsers/chromium*/chrome-linux/chrome 2>/dev/null | head -1").toString().trim();
const b = await chromium.launch({ executablePath: EXE, args: ["--no-sandbox"] });
const p = await (await b.newContext({ viewport: { width: 1440, height: 950 } })).newPage();
await p.goto("http://localhost:3922/team", { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.screenshot({ path: `${process.env.SHOT_DIR}/AI-status-panel.png` });
const t = (await p.textContent("body")) || "";
console.log("panel present:", /AI Provider Status/i.test(t), "| mode live:", /\bLive\b/.test(t), "| cost:", /Est\. AI cost/i.test(t));
await b.close();
